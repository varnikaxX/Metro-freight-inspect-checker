import type { ScanResponse } from "./types";
import { deriveVerdict } from "./types";
import { getFieldConfig } from "./field-config";
import { formatDateTime } from "./utils";

/**
 * The backend does not currently generate `pdf_report_url` (see
 * services/supabase_client.py — the column exists but nothing populates
 * it yet). Until that ships, the report is composed client-side from the
 * ScanResponse payload so the "Download Compliance Report" action always
 * works end to end.
 */
export async function downloadComplianceReport(scan: ScanResponse) {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const verdict = deriveVerdict(scan);
  const margin = 48;
  let y = margin;
  const pageWidth = doc.internal.pageSize.getWidth();
  const contentWidth = pageWidth - margin * 2;

  const verdictColor: Record<string, [number, number, number]> = {
    PASS: [30, 153, 115],
    VIOLATIONS: [214, 52, 71],
    MANUAL_REVIEW: [232, 163, 61],
  };
  const verdictLabel: Record<string, string> = {
    PASS: "COMPLIANT",
    VIOLATIONS: "VIOLATIONS DETECTED",
    MANUAL_REVIEW: "MANUAL REVIEW REQUIRED",
  };

  // Header band
  doc.setFillColor(10, 15, 26);
  doc.rect(0, 0, pageWidth, 96, "F");
  doc.setTextColor(217, 188, 130);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(9);
  doc.text("LEGAL METROLOGY (PACKAGED COMMODITIES) RULES, 2011", margin, 34);
  doc.setTextColor(250, 248, 246);
  doc.setFontSize(18);
  doc.text("Compliance Verification Report", margin, 60);
  doc.setFontSize(9);
  doc.setTextColor(200, 200, 200);
  doc.text(`Scan ID: ${scan.id}`, margin, 80);

  y = 130;

  // Verdict pill
  const [r, g, b] = verdictColor[verdict];
  doc.setFillColor(r, g, b);
  doc.roundedRect(margin, y, 220, 30, 6, 6, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(verdictLabel[verdict], margin + 14, y + 20);
  y += 55;

  doc.setTextColor(20, 20, 20);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`Status: ${scan.status}`, margin, y);
  doc.text(`Scanned: ${formatDateTime(scan.created_at)}`, margin + 220, y);
  y += 26;

  // Extracted fields
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.text("Extracted Attributes", margin, y);
  y += 10;
  doc.setDrawColor(220, 220, 220);
  doc.line(margin, y, margin + contentWidth, y);
  y += 20;

  doc.setFontSize(10);
  scan.extracted_fields.forEach((field) => {
    if (y > 760) {
      doc.addPage();
      y = margin;
    }
    const cfg = getFieldConfig(field.field_name);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(30, 30, 30);
    doc.text(cfg.label, margin, y);

    doc.setFont("helvetica", "normal");
    if (field.is_present) {
      doc.setTextColor(30, 153, 115);
      doc.text("PRESENT", margin + 260, y);
      doc.setTextColor(60, 60, 60);
      const value = field.field_value ?? "—";
      const lines = doc.splitTextToSize(value, contentWidth - 340);
      doc.text(lines, margin + 340, y);
      y += 14 * Math.max(lines.length, 1);
    } else {
      doc.setTextColor(214, 52, 71);
      doc.text("MISSING", margin + 260, y);
      y += 14;
    }
    y += 6;
  });

  y += 14;
  if (y > 720) {
    doc.addPage();
    y = margin;
  }

  // Violations
  doc.setFont("helvetica", "bold");
  doc.setFontSize(13);
  doc.setTextColor(20, 20, 20);
  doc.text(`Violations (${scan.violations.length})`, margin, y);
  y += 10;
  doc.line(margin, y, margin + contentWidth, y);
  y += 20;

  if (scan.violations.length === 0) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
    doc.setTextColor(30, 153, 115);
    doc.text("No violations detected. All mandatory declarations present.", margin, y);
    y += 20;
  } else {
    doc.setFontSize(10);
    scan.violations.forEach((v) => {
      if (y > 760) {
        doc.addPage();
        y = margin;
      }
      doc.setFont("helvetica", "bold");
      doc.setTextColor(214, 52, 71);
      doc.text(v.rule_code, margin, y);
      y += 14;
      doc.setFont("helvetica", "normal");
      doc.setTextColor(60, 60, 60);
      const lines = doc.splitTextToSize(v.description, contentWidth);
      doc.text(lines, margin, y);
      y += 14 * lines.length + 10;
    });
  }

  // Footer
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    doc.text(
      "Generated by Metrology Verify — for field enforcement use. Not a substitute for statutory adjudication.",
      margin,
      820
    );
    doc.text(`Page ${i} of ${pageCount}`, pageWidth - margin - 60, 820);
  }

  doc.save(`compliance-report-${scan.id.slice(0, 8)}.pdf`);
}
